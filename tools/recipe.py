#!/usr/bin/env python3
"""CPU-safe helper for the DeepSeek-V4.1-Flash TP8/EP8 8x DGX Spark recipe.

Scope and guarantees
--------------------
* Standard library only. No third-party imports, no containers, no GPU work.
* Env files are parsed as data. Values are never passed through a shell:
  command substitution (``$(...)``), backticks, control characters and NUL bytes
  are rejected outright.
* Credentials are out of scope. Non-empty ``API_KEY``/``HF_TOKEN`` style keys are
  rejected by name only; their values are never read back into output, argv or
  a rendered file.
* ``prepare`` is source-only: it creates a git checkout pinned to
  ``config/recipe.lock.json`` and applies the bundled launcher patch. It never
  downloads weights, builds an image or starts a server.
* ``render`` writes ``.env.tp8`` plus a ``start-tp8.sh`` wrapper into an already
  prepared runtime. The measured profile is emitted last and therefore overrides
  inherited flags.
* ``run`` is a dry run unless BOTH ``--execute`` and ``--ack-unqualified-port``
  are supplied.

Limitations (do not read these as deployment claims)
----------------------------------------------------
* A fresh checkout/render is **not** serving-qualified. The measured ring used
  retained per-node images; see the lock ``status``.
* The lock pins the recipe model revision but does NOT assert a hash of the
  measured weight files; ``MODEL_DIR`` contents are not verified here.
* CPU tests establish parsing, pinning and argv shape only. They do not
  establish native deployment, correctness or performance.
"""

