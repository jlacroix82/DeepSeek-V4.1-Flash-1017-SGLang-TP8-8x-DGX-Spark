class RecipeError(Exception):
    """User-facing failure. Message must never contain a secret value."""


def repo_root() -> Path:
    return Path(__file__).resolve().parents[1]


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return digest.hexdigest()


def split_list(value: str):
    return [part for part in re.split(r"[,\s]+", str(value).strip()) if part]


def is_ipv4(value: str) -> bool:
    return bool(IPV4_RE.match(str(value).strip()))


def looks_placeholder(value: str) -> bool:
    low = str(value).lower()
    if low.startswith(("set_", "set-")):
        return True
    return any(marker in low for marker in PLACEHOLDER_MARKERS)


def load_lock(path: Path) -> dict:
    if not path.is_file():
        raise RecipeError(f"lock file not found: {path}")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise RecipeError(f"cannot read lock {path}: {exc}")
    if not isinstance(data, dict):
        raise RecipeError(f"lock {path} is not a JSON object")
    for key in ("upstream_url", "upstream_commit", "base_image", "model_id",
                "recipe_model_revision"):
        if not str(data.get(key, "")).strip():
            raise RecipeError(f"lock {path} is missing {key}")
    url = str(data["upstream_url"])
    if not url.startswith("https://"):
        raise RecipeError("upstream_url must be an https:// URL")
    if not SHA1_RE.match(str(data["upstream_commit"])):
        raise RecipeError("upstream_commit must be a 40-hex SHA-1")
    if not SHA1_RE.match(str(data["recipe_model_revision"])):
        raise RecipeError("recipe_model_revision must be a 40-hex SHA-1")
    if "@sha256:" not in str(data["base_image"]):
        raise RecipeError("base_image must be pinned by @sha256 digest")
    digest = str(data["base_image"]).rsplit("@sha256:", 1)[1]
    if not SHA256_RE.match(digest):
        raise RecipeError("base_image digest is not a 64-hex sha256")
    canonical_from_lock(data)
    return data


def canonical_from_lock(lock: dict) -> "OrderedDict[str, str]":
    measured = lock.get("measured_profile")
    if not isinstance(measured, dict):
        raise RecipeError("lock has no measured_profile object")
    out: "OrderedDict[str, str]" = OrderedDict()
    for key, expected in CANONICAL_PROFILE.items():
        if key not in measured:
            raise RecipeError(f"lock measured_profile is missing {key}")
        value = measured[key]
        if isinstance(value, bool) or not isinstance(value, (int, float, str)):
            raise RecipeError(f"lock measured_profile.{key} has an unusable type")
        rendered = str(value).strip()
        if rendered != expected:
            raise RecipeError(
                f"lock measured_profile.{key}={rendered!r} disagrees with the "
                f"built-in TP8 profile {expected!r}"
            )
        out[key] = expected
    return out


def _same_number(left: str, right: str) -> bool:
    if left == right:
        return True
    try:
        return float(left) == float(right)
    except ValueError:
        return False


def _reject_value(name: str, raw: str) -> None:
    if any(ord(ch) < 32 for ch in raw):
        raise RecipeError(f"{name}: control characters/newlines are not allowed")
    if "`" in raw:
        raise RecipeError(f"{name}: backticks are not allowed (no shell evaluation)")
    if "$(" in raw:
        raise RecipeError(f"{name}: command substitution '$(' is not allowed")
    if "\x7f" in raw:
        raise RecipeError(f"{name}: DEL character is not allowed")


def _unquote(name: str, raw: str) -> str:
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in ("'", '"'):
        inner = raw[1:-1]
        if raw[0] in inner:
            raise RecipeError(f"{name}: unbalanced {raw[0]} quoting")
        return inner
    if raw[:1] in ("'", '"') or raw[-1:] in ("'", '"'):
        raise RecipeError(f"{name}: unbalanced quoting")
    return raw


def parse_env_file(path: Path) -> "OrderedDict[str, str]":
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise RecipeError(f"cannot read env file {path}: {exc}")
    if "\x00" in text:
        raise RecipeError(f"{path}: NUL byte in env file")
    text = text.replace("\r\n", "\n")
    if "\r" in text:
        raise RecipeError(f"{path}: bare carriage return in env file")

    cfg: "OrderedDict[str, str]" = OrderedDict()
    seen_line: dict = {}
    for lineno, raw_line in enumerate(text.split("\n"), 1):
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export "):].lstrip()
        if "=" not in line:
            raise RecipeError(f"{path}:{lineno}: expected NAME=value")
        name, raw_value = line.split("=", 1)
        name = name.strip()
        raw_value = raw_value.strip()
        if not NAME_RE.match(name):
            raise RecipeError(f"{path}:{lineno}: invalid variable name")
        if name in cfg:
            raise RecipeError(
                f"{path}:{lineno}: duplicate {name} (first set on line {seen_line[name]})"
            )
        _reject_value(name, raw_value)
        value = _unquote(name, raw_value)

        if name in SECRET_EMPTY_ONLY:
            if value:
                raise RecipeError(
                    f"{name} is set but credentials are out of scope for this recipe "
                    f"tool; leave it empty and supply auth out of band"
                )
        elif SENSITIVE_RE.search(name):
            raise RecipeError(
                f"{name} looks sensitive; this tool refuses to read or echo "
                f"credential-bearing keys"
            )
        if name == "DSV41_LAUNCHER":
            raise RecipeError(
                "DSV41_LAUNCHER is not configurable here: the TP8 profile uses the "
                "upstream non-tp4 launcher path plus the bundled patch"
            )
        cfg[name] = value
        seen_line[name] = lineno
    if not cfg:
        raise RecipeError(f"{path}: no NAME=value entries found")
    return cfg


def validate_config(cfg: dict, *, plan_mode: bool):
    errors = []
    warnings = []
    placeholder_keys = []

    missing = [key for key in REQUIRED_KEYS if not str(cfg.get(key, "")).strip()]
    if missing:
        errors.append("missing required keys: " + ", ".join(missing))

    ips = split_list(cfg.get("WORKER_IPS", ""))
    hosts = split_list(cfg.get("WORKER_HOSTS", ""))
    head_ip = str(cfg.get("HEAD_IP", "")).strip()
    head_host = str(cfg.get("HEAD_HOST", "")).strip()

    if len(ips) != WORKERS:
        errors.append(f"WORKER_IPS must list exactly {WORKERS} addresses (got {len(ips)})")
    if len(hosts) != WORKERS:
        errors.append(f"WORKER_HOSTS must list exactly {WORKERS} names (got {len(hosts)})")
    if len(set(ips)) != len(ips):
        errors.append("WORKER_IPS contains duplicates")
    if len(set(hosts)) != len(hosts):
        errors.append("WORKER_HOSTS contains duplicates")

    def soft_or_hard(key, value, message):
        if plan_mode:
            warnings.append(f"{key}: {message} (plan only; render/run will refuse)")
            placeholder_keys.append(key)
        else:
            errors.append(f"{key}: {message}")

    for value in ips:
        if not is_ipv4(value):
            soft_or_hard("WORKER_IPS", value, f"{value!r} is not an IPv4 address")
    if head_ip and not is_ipv4(head_ip):
        soft_or_hard("HEAD_IP", head_ip, f"{head_ip!r} is not an IPv4 address")
    for value in hosts:
        if not HOST_RE.match(value):
            soft_or_hard("WORKER_HOSTS", value, f"{value!r} is not a hostname")
    if head_host and not HOST_RE.match(head_host):
        soft_or_hard("HEAD_HOST", head_host, f"{head_host!r} is not a hostname")

    if head_ip and head_ip in ips:
        errors.append("HEAD_IP must not also appear in WORKER_IPS")
    if head_host and head_host in hosts:
        errors.append("HEAD_HOST must not also appear in WORKER_HOSTS")

    for key in PATH_KEYS:
        value = str(cfg.get(key, "")).strip()
        if not value:
            continue
        if "$" in value:
            soft_or_hard(key, value, "must be an explicit absolute path, not a variable")
        elif not posixpath.isabs(value):
            soft_or_hard(key, value, "must be an absolute path")
        elif ".." in Path(value).parts:
            errors.append(f"{key}: must not contain '..'")

    for key in ("FABRIC_IFACE", "NCCL_SOCKET_IFNAME", "GLOO_SOCKET_IFNAME", "IB_HCA"):
        value = str(cfg.get(key, "")).strip()
        if not value:
            continue
        if not IFACE_RE.match(value):
            errors.append(f"{key}: {value!r} is not a plain interface/HCA list")
        elif key == "FABRIC_IFACE" and "," in value:
            errors.append("FABRIC_IFACE must be a single interface")

    for key, value in cfg.items():
        if looks_placeholder(value):
            placeholder_keys.append(key)
    if placeholder_keys:
        unique = sorted(set(placeholder_keys))
        message = "placeholder values present: " + ", ".join(unique)
        if plan_mode:
            warnings.append(message + " (plan only; render/run will refuse)")
        else:
            errors.append(message + "; edit the env file before render/run")

    return errors, warnings


def effective_env(cfg: dict, lock: dict) -> "OrderedDict[str, str]":
    """User keys first, then pinned model id, then the canonical profile last."""
    out: "OrderedDict[str, str]" = OrderedDict()
    for key, value in cfg.items():
        if key in PROFILE_OWNED_KEYS or key in CANONICAL_PROFILE:
            continue
        if key in SECRET_EMPTY_ONLY or key in ("HF_REPO", "HF_REVISION"):
            continue
        if key in ("WORKER_IPS", "WORKER_HOSTS"):
            value = " ".join(split_list(value))
        out[key] = value
    out["HF_REPO"] = str(lock["model_id"])
    out["HF_REVISION"] = str(lock["recipe_model_revision"])
    out["API_KEY"] = ""
    for key, value in CANONICAL_PROFILE.items():
        out[key] = value
    return out


def render_env_text(env: "OrderedDict[str, str]", lock_commit: str) -> str:
    lines = [
        "# .env.tp8 -- generated by tools/recipe.py; do not hand-edit.",
        f"# upstream commit {lock_commit}",
        "# Measured profile is emitted last: it overrides inherited/user values.",
        "# No credentials: API_KEY is blank by policy (auth is out of scope).",
        "",
    ]
    for key, value in env.items():
        lines.append(f"{key}={shlex.quote(value)}")
    lines.append("")
    return "\n".join(lines)


def atomic_write(path: Path, text: str, mode: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(prefix=path.name + ".", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def git(args, cwd: Path, *, quiet=False):
    if not quiet:
        print("$ git " + shlex.join([str(a) for a in args]))
    try:
        return subprocess.run(
            ["git", *[str(a) for a in args]],
            cwd=str(cwd),
            text=True,
            capture_output=True,
            shell=False,
        )
    except OSError as exc:
        raise RecipeError(f"cannot run git: {exc}")


def git_ok(args, cwd: Path, *, what: str, quiet=False) -> str:
    proc = git(args, cwd, quiet=quiet)
    if proc.returncode != 0:
        detail = (proc.stderr or proc.stdout or "").strip().splitlines()
        tail = detail[-1] if detail else f"exit {proc.returncode}"
        raise RecipeError(f"git {what} failed: {tail}")
    return (proc.stdout or "").strip()


def repo_patch() -> Path:
    return repo_root() / "patches" / "upstream-tp8-launcher.patch"


def require_prepared(runtime: Path, lock: dict, patch: Path) -> dict:
    if not runtime.is_dir():
        raise RecipeError(f"runtime directory does not exist: {runtime}")
    marker_path = runtime / MARKER_NAME
    if not marker_path.is_file():
        raise RecipeError(
            f"{runtime} has no {MARKER_NAME}; run 'prepare' into it first"
        )
    try:
        marker = json.loads(marker_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise RecipeError(f"unreadable prepare marker {marker_path}: {exc}")
    expected = {
        "upstream_commit": str(lock["upstream_commit"]),
        "upstream_url": str(lock["upstream_url"]),
        "patch_sha256": sha256_file(patch),
    }
    for key, want in expected.items():
        got = str(marker.get(key, ""))
        if got != want:
            raise RecipeError(
                f"prepare marker mismatch on {key}: marker={got!r} expected={want!r}"
            )
    head = git_ok(["rev-parse", "HEAD"], runtime, what="rev-parse HEAD", quiet=True)
    if head != expected["upstream_commit"]:
        raise RecipeError(
            f"runtime HEAD {head} does not match pinned commit "
            f"{expected['upstream_commit']}"
        )
    reverse = git(["apply", "--check", "-R", str(patch)], runtime, quiet=True)
    if reverse.returncode != 0:
        raise RecipeError(
            "bundled launcher patch is not applied (or does not reverse cleanly); "
            "re-run prepare into a fresh directory"
        )
    return marker


def cmd_plan(args) -> int:
    root = repo_root()
    lock_path = Path(args.lock).expanduser() if args.lock else root / "config" / "recipe.lock.json"
    lock = load_lock(lock_path)
    patch = repo_patch()
    if not patch.is_file():
        raise RecipeError(f"bundled patch missing: {patch}")
    env_path = Path(args.env_file).expanduser()
    cfg = parse_env_file(env_path)
    errors, warnings = validate_config(cfg, plan_mode=True)
    if errors:
        raise RecipeError("; ".join(errors))

    ips = split_list(cfg["WORKER_IPS"])
    hosts = split_list(cfg["WORKER_HOSTS"])
    print("TP8 recipe plan - CPU only; no source, container, GPU or network action taken")
    print(f"tool_version={TOOL_VERSION}")
    print(f"lock={lock_path} sha256={sha256_file(lock_path)}")
    print(f"upstream={lock['upstream_url']}@{lock['upstream_commit']}")
    print(
        f"model={lock['model_id']}@{lock['recipe_model_revision']} "
        "(revision pin only; weight contents are NOT hash-verified)"
    )
    print(f"base_image={lock['base_image']}")
    print(f"status={lock.get('status', '')}")
    print(f"env={env_path} keys={len(cfg)}")
    print(f"nodes=1 head + {len(ips)} workers = {len(ips) + 1}")
    print(f"worker_ips={len(ips)} unique={len(set(ips))}")
    print(f"worker_hosts={len(hosts)} unique={len(set(hosts))}")
    print("canonical measured profile (render emits these last, overriding inherited values):")
    for key, value in CANONICAL_PROFILE.items():
        print(f"  {key}={value}")
    if "DSPARK_BLOCK_SIZE" in cfg:
        print("note: DSPARK_BLOCK_SIZE=5 is the upstream block setting; it maps to six")
        print("      configured speculative tokens natively (documented, not asserted).")

    diverged = []
    for key, value in CANONICAL_PROFILE.items():
        if key in cfg and not _same_number(str(cfg[key]).strip(), value):
            diverged.append(f"{key}: env={cfg[key]!r} canonical={value!r}")
    if diverged:
        print("divergences (will be overridden by render):")
        for line in diverged:
            print(f"  {line}")
    ignored = [key for key in cfg if key in PROFILE_OWNED_KEYS]
    if ignored:
        print("ignored profile-owned keys: " + ", ".join(sorted(ignored)))
    if "DSV41_LAUNCHER" in cfg:
        print("warning: DSV41_LAUNCHER in env will be dropped (non-tp4 path is measured)")
    if str(cfg.get("HF_REPO", "")) and str(cfg["HF_REPO"]) != str(lock["model_id"]):
        print("warning: HF_REPO differs from the lock and will be pinned by render")
    if str(cfg.get("HF_REVISION", "")) and str(cfg["HF_REVISION"]) != str(lock["recipe_model_revision"]):
        print("warning: HF_REVISION differs from the lock and will be pinned by render")
    for warning in warnings:
        print(f"warning: {warning}")

    directory = Path("~/tp8-runtime").expanduser()
    print("next steps (no action taken now):")
    print(f"  {shlex.join([sys.executable, str(root / 'tools' / 'recipe.py'), 'prepare', '--directory', str(directory)])}")
    print(f"  {shlex.join([sys.executable, str(root / 'tools' / 'recipe.py'), 'render', '--env-file', str(env_path), '--runtime', str(directory)])}")
    print(f"  {shlex.join([sys.executable, str(root / 'tools' / 'recipe.py'), 'run', 'doctor', '--env-file', str(env_path), '--runtime', str(directory)])}")
    print("  # real execution: append --execute --ack-unqualified-port")
    print("limitations: a fresh prepare/render is not serving-qualified; CPU checks")
    print("cannot establish native deployment, correctness or performance.")
    return 0


def cmd_prepare(args) -> int:
    root = repo_root()
    lock_path = Path(args.lock).expanduser() if args.lock else root / "config" / "recipe.lock.json"
    lock = load_lock(lock_path)
    patch = Path(args.patch).expanduser().resolve() if args.patch else repo_patch()
    if not patch.is_file():
        raise RecipeError(f"bundled patch missing: {patch}")
    patch_sha = sha256_file(patch)
    commit = str(lock["upstream_commit"])
    url = str(lock["upstream_url"])
    directory = Path(args.directory).expanduser().resolve()

    home = Path.home().resolve()
    if directory == Path("/") or directory == home:
        raise RecipeError(f"refusing unsafe prepare directory: {directory}")
    allowed_runtime_root = (root / ".runtime").resolve()
    inside_ignored_runtime = directory == allowed_runtime_root or allowed_runtime_root in directory.parents
    if directory == root or directory in root.parents or (root in directory.parents and not inside_ignored_runtime):
        raise RecipeError(
            "refusing to prepare into the recipe root, its ancestor, or a non-.runtime source path"
        )

    marker_path = directory / MARKER_NAME
    if directory.exists():
        if not directory.is_dir():
            raise RecipeError(f"{directory} exists and is not a directory")
        if marker_path.is_file():
            try:
                marker = json.loads(marker_path.read_text(encoding="utf-8"))
            except (OSError, ValueError) as exc:
                raise RecipeError(f"unreadable marker {marker_path}: {exc}")
            if str(marker.get("upstream_commit", "")) != commit:
                raise RecipeError(
                    f"{directory} was prepared for commit {marker.get('upstream_commit')!r}, "
                    f"lock pins {commit!r}; refusing to reuse"
                )
            if str(marker.get("patch_sha256", "")) != patch_sha:
                raise RecipeError(
                    f"{directory} was prepared with a different launcher patch; refusing to reuse"
                )
            head = git_ok(["rev-parse", "HEAD"], directory, what="rev-parse HEAD", quiet=True)
            if head != commit:
                raise RecipeError(
                    f"{directory} marker says {commit} but HEAD is {head}; refusing to reuse"
                )
            print(f"already prepared: {directory} (HEAD {commit}, patch {patch.name})")
            return 0
        if any(directory.iterdir()):
            raise RecipeError(
                f"{directory} exists, is not empty, and has no {MARKER_NAME}; "
                "refusing to touch a tree this tool does not own"
            )
    else:
        directory.mkdir(parents=True)

    if not subprocess_which_git():
        raise RecipeError("git is required for prepare but was not found on PATH")

    git_ok(["init", "-q"], directory, what="init")
    remotes = git_ok(["remote"], directory, what="remote", quiet=True).split()
    if "origin" in remotes:
        git_ok(["remote", "set-url", "origin", url], directory, what="remote set-url")
    else:
        git_ok(["remote", "add", "origin", url], directory, what="remote add")
    git_ok(["fetch", "--depth", "1", "origin", commit], directory, what="fetch pinned commit")
    git_ok(
        ["-c", "advice.detachedHead=false", "checkout", "-q", "--detach", commit],
        directory,
        what="checkout",
    )
    head = git_ok(["rev-parse", "HEAD"], directory, what="rev-parse HEAD", quiet=True)
    if head != commit:
        raise RecipeError(f"checkout produced HEAD {head}, expected {commit}")

    check = git(["apply", "--check", str(patch)], directory)
    if check.returncode != 0:
        detail = ((check.stderr or "") + (check.stdout or "")).strip().splitlines()
        raise RecipeError(
            "launcher patch does not apply cleanly to the pinned tree "
            f"(upstream drift?): {detail[-1] if detail else 'git apply --check failed'}"
        )
    git_ok(["apply", str(patch)], directory, what="apply launcher patch")

    marker = {
        "schema_version": SCHEMA_VERSION,
        "tool_version": TOOL_VERSION,
        "upstream_url": url,
        "upstream_commit": commit,
        "patch_sha256": patch_sha,
        "patch_path": patch.name,
        "lock_sha256": sha256_file(lock_path),
        "prepared_utc": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "source_only": True,
        "weights_downloaded": False,
        "image_built": False,
    }
    atomic_write(marker_path, json.dumps(marker, indent=2, sort_keys=True) + "\n", 0o644)
    print(f"prepared: {directory}")
    print(f"HEAD={commit}")
    print(f"patch={patch.name} sha256={patch_sha}")
    print(f"marker={MARKER_NAME}")
    print("no weights downloaded, no image built, no container or GPU action taken")
    return 0


def subprocess_which_git() -> bool:
    try:
        return subprocess.run(
            ["git", "--version"], text=True, capture_output=True, shell=False
        ).returncode == 0
    except OSError:
        return False


def verify_rendered_env(path: Path) -> None:
    cfg = parse_env_file(path)
    for key, expected in CANONICAL_PROFILE.items():
        got = str(cfg.get(key, ""))
        if got != expected:
            raise RecipeError(
                f"rendered {ENV_NAME} has {key}={got!r}, expected {expected!r}"
            )
    if cfg.get("API_KEY", "") != "":
        raise RecipeError(f"rendered {ENV_NAME} must keep API_KEY blank")
    if cfg.get("HF_REPO", "") == "" or cfg.get("HF_REVISION", "") == "":
        raise RecipeError(f"rendered {ENV_NAME} is missing the model pin")


def cmd_render(args) -> int:
    root = repo_root()
    lock_path = Path(args.lock).expanduser() if args.lock else root / "config" / "recipe.lock.json"
    lock = load_lock(lock_path)
    patch = repo_patch()
    if not patch.is_file():
        raise RecipeError(f"bundled patch missing: {patch}")
    env_path = Path(args.env_file).expanduser()
    cfg = parse_env_file(env_path)
    errors, warnings = validate_config(cfg, plan_mode=False)
    if errors:
        raise RecipeError("; ".join(errors))
    runtime = Path(args.runtime).expanduser().resolve()
    require_prepared(runtime, lock, patch)

    env = effective_env(cfg, lock)
    atomic_write(runtime / ENV_NAME, render_env_text(env, str(lock["upstream_commit"])), 0o600)
    atomic_write(runtime / WRAPPER_NAME, WRAPPER_TEMPLATE, 0o755)
    verify_rendered_env(runtime / ENV_NAME)

    print(f"rendered: {runtime / ENV_NAME} (0600)")
    print(f"wrapper:  {runtime / WRAPPER_NAME} (0755)")
    print("canonical profile emitted last:")
    for key, value in CANONICAL_PROFILE.items():
        print(f"  {key}={value}")
    print("launcher: upstream start.sh, DSV41_LAUNCHER unset (no tp4 switch)")
    print("credentials: API_KEY blank; no secret values written")
    for warning in warnings:
        print(f"warning: {warning}")
    print("NOTE: a fresh render is NOT serving-qualified; real runs need")
    print("--execute --ack-unqualified-port and a full serving review.")
    return 0


def cmd_run(args) -> int:
    root = repo_root()
    lock_path = Path(args.lock).expanduser() if args.lock else root / "config" / "recipe.lock.json"
    lock = load_lock(lock_path)
    patch = repo_patch()
    env_path = Path(args.env_file).expanduser()
    cfg = parse_env_file(env_path)
    errors, _ = validate_config(cfg, plan_mode=False)
    if errors:
        raise RecipeError("; ".join(errors))
    runtime = Path(args.runtime).expanduser().resolve()
    wrapper = runtime / WRAPPER_NAME
    argv = [str(wrapper), args.action]
    child_env = {key: os.environ[key] for key in PASS_ENV_KEYS if key in os.environ}
    child_env.setdefault("PATH", "/usr/local/bin:/usr/bin:/bin")
    child_env.setdefault("HOME", str(Path.home()))

    if not args.execute:
        print("DRY RUN - no command executed, no files written")
        print(f"action={args.action}")
        print(f"cwd={runtime}")
        print(f"argv={shlex.join(argv)}")
        print(f"env_keys_passed={','.join(sorted(child_env))}")
        print(f"env_file={runtime / ENV_NAME}")
        print(f"runtime_prepared={(runtime / MARKER_NAME).is_file()}")
        if not wrapper.is_file():
            print(f"note: wrapper does not exist yet; run render --runtime {runtime}")
        print("real execution requires BOTH --execute and --ack-unqualified-port")
        if args.action == "serve":
            print("note: a fresh render is not serving-qualified")
        return 0

    if not args.ack_unqualified_port:
        raise RecipeError(
            "refusing real execution: pass --execute AND --ack-unqualified-port "
            "to acknowledge the fresh runtime is not serving-qualified"
        )
    if not wrapper.is_file():
        raise RecipeError(f"no wrapper at {wrapper}; run render first")
    if not (runtime / ENV_NAME).is_file():
        raise RecipeError(f"no {ENV_NAME} at {runtime}; run render first")
    require_prepared(runtime, lock, patch)
    verify_rendered_env(runtime / ENV_NAME)

    print(f"EXECUTING: {shlex.join(argv)} (cwd={runtime})")
    proc = subprocess.run(argv, cwd=str(runtime), env=child_env, shell=False)
    print(f"exit={proc.returncode}")
    return int(proc.returncode)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="recipe.py",
        description=(
            "CPU-safe TP8/EP8 recipe helper: plan, source-only prepare, render and "
            "dry-run by default. No build, weights or serving is performed here."
        ),
    )
    parser.add_argument("--version", action="version", version=f"recipe.py {TOOL_VERSION}")
    sub = parser.add_subparsers(dest="command", required=True)

    def add_lock(p):
        p.add_argument("--lock", default=None,
                       help="recipe lock path (default: config/recipe.lock.json)")

    plan = sub.add_parser("plan", help="validate env + print pin/profile plan (no action)")
    plan.add_argument("--env-file", required=True)
    add_lock(plan)
    plan.set_defaults(func=cmd_plan)

    prepare = sub.add_parser(
        "prepare", help="source-only pinned git checkout + launcher patch"
    )
    prepare.add_argument("--directory", required=True)
    prepare.add_argument("--patch", default=None,
                         help="patch path (default: patches/upstream-tp8-launcher.patch)")
    add_lock(prepare)
    prepare.set_defaults(func=cmd_prepare)

    render = sub.add_parser(
        "render", help="write .env.tp8 + start-tp8.sh into a prepared runtime"
    )
    render.add_argument("--env-file", required=True)
    render.add_argument("--runtime", required=True)
    add_lock(render)
    render.set_defaults(func=cmd_render)

    run = sub.add_parser("run", help="dry-run (default) or execute one launcher action")
    run.add_argument("action", choices=ACTIONS)
    run.add_argument("--env-file", required=True)
    run.add_argument("--runtime", required=True)
    run.add_argument("--execute", action="store_true",
                     help="actually invoke the wrapper (requires --ack-unqualified-port)")
    run.add_argument("--ack-unqualified-port", action="store_true",
                     help="acknowledge the fresh runtime is not serving-qualified")
    add_lock(run)
    run.set_defaults(func=cmd_run)
    return parser


def main(argv=None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return int(args.func(args))
    except RecipeError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())